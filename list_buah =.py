list_buah = ['pisang','nanas','melon','durian']
print(list_buah)
# ubah data pertama
list_buah[0] = 'Jeruk'
print(list_buah)
# ubah data terakhir
list_buah[-1] = 'Mangga'
print(list_buah)

#ubah data dalam range
list_buah[1:3] = ['Naga','Pepaya']
print(list_buah)

#tambah data dibelakang list
list_buah.append('sirsak')
print(list_buah)

#tambah data di awal list
list_buah.insert(0,'Jambu')
print(list_buah)

#tambah data di index mana pun dalam list
list_buah.indsert(2,'Mangggis')
print(list_buah)

